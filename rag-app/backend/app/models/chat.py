"""
models/chat.py — Pydantic v2 request / response schemas for the entire API.

These are the single source of truth for:
  - /api/chat    (chat completion with streaming)
  - /api/ingest  (document upload & ingestion)
  - Shared types (sources, messages, conversation history)
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import UUID, uuid4

from pydantic import BaseModel, Field, field_validator, model_validator


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class MessageRole(str, Enum):
    user = "user"
    assistant = "assistant"
    system = "system"


class IngestStatus(str, Enum):
    pending = "pending"
    processing = "processing"
    completed = "completed"
    failed = "failed"


class DocumentType(str, Enum):
    pdf = "pdf"
    txt = "txt"
    docx = "docx"
    unknown = "unknown"


# ---------------------------------------------------------------------------
# Shared primitives
# ---------------------------------------------------------------------------

class SourceReference(BaseModel):
    """A single source document chunk cited in an answer."""

    document_id: str = Field(..., description="Unique identifier of the source document")
    file_name: str = Field(..., description="Original file name")
    page: Optional[int] = Field(None, description="Page number (PDF only)")
    chunk_index: int = Field(..., description="Chunk index within the document")
    score: float = Field(..., ge=0.0, le=1.0, description="Relevance score after reranking")
    excerpt: str = Field(..., max_length=500, description="Short text excerpt from the chunk")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ChatMessage(BaseModel):
    """A single turn in a conversation."""

    role: MessageRole
    content: str = Field(..., min_length=1, max_length=32_000)
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    @field_validator("content", mode="before")
    @classmethod
    def _strip_content(cls, v: str) -> str:
        return v.strip()


# ---------------------------------------------------------------------------
# Chat request / response
# ---------------------------------------------------------------------------

class ChatRequest(BaseModel):
    """
    POST /api/chat

    The frontend sends the full conversation history so the backend can
    maintain context without server-side session state.
    """

    session_id: UUID = Field(
        default_factory=uuid4,
        description="Client-generated session UUID for conversation continuity",
    )
    query: str = Field(
        ...,
        min_length=1,
        max_length=4_000,
        description="The user's current question",
    )
    history: List[ChatMessage] = Field(
        default_factory=list,
        max_length=20,  # guard against excessively long context
        description="Previous turns in the conversation (most-recent last)",
    )
    # Optional per-request overrides
    top_k: Optional[int] = Field(
        None, ge=1, le=50,
        description="Override RETRIEVAL_TOP_K for this request"
    )
    filters: Optional[Dict[str, Any]] = Field(
        None,
        description="Metadata filters, e.g. {\"file_name\": \"policy.pdf\"}",
    )
    stream: bool = Field(
        default=True,
        description="Whether to stream the response via SSE",
    )

    @field_validator("query", mode="before")
    @classmethod
    def _strip_query(cls, v: str) -> str:
        return v.strip()

    @model_validator(mode="after")
    def _history_roles_alternate(self) -> "ChatRequest":
        """
        Soft-validate that history alternates user/assistant roles.
        We warn rather than reject to be lenient with client bugs.
        """
        roles = [m.role for m in self.history]
        for i, role in enumerate(roles):
            if i > 0 and role == roles[i - 1]:
                # Two consecutive same-role messages — silently pass but log
                break
        return self


class ChatResponse(BaseModel):
    """
    POST /api/chat  (non-streaming response)

    For streaming responses the backend emits SSE chunks; this schema
    describes the final aggregated payload (also returned in non-stream mode).
    """

    session_id: UUID
    answer: str = Field(..., description="The generated answer text")
    sources: List[SourceReference] = Field(
        default_factory=list,
        description="Cited source chunks used to generate the answer",
    )
    query_expansions: List[str] = Field(
        default_factory=list,
        description="Additional queries generated by multi-query retrieval",
    )
    fallback: bool = Field(
        default=False,
        description="True when no relevant documents were found and the LLM answered from general knowledge",
    )
    latency_ms: Optional[float] = Field(
        None, description="Total server-side processing time in milliseconds"
    )


class StreamChunk(BaseModel):
    """
    SSE payload for a single streaming token chunk.

    The frontend should accumulate `delta` values until `done=True`,
    then render `sources` from the final chunk.
    """

    delta: str = Field(default="", description="Incremental token text")
    done: bool = Field(default=False, description="True on the final chunk")
    sources: List[SourceReference] = Field(
        default_factory=list,
        description="Populated only on the final chunk (done=True)",
    )
    fallback: bool = Field(default=False)
    error: Optional[str] = Field(
        None, description="Error message if streaming failed mid-stream"
    )


# ---------------------------------------------------------------------------
# Ingest request / response
# ---------------------------------------------------------------------------

class IngestResponse(BaseModel):
    """
    POST /api/ingest  (file upload)

    Returned immediately; use document_id to poll status if needed.
    """

    document_id: str = Field(..., description="UUID assigned to the ingested document")
    file_name: str
    file_size_bytes: int
    document_type: DocumentType
    status: IngestStatus = IngestStatus.processing
    chunk_count: Optional[int] = Field(
        None, description="Number of chunks created (populated when status=completed)"
    )
    message: str = Field(default="Document received and queued for ingestion")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )


class IngestStatusResponse(BaseModel):
    """
    GET /api/ingest/{document_id}/status
    """

    document_id: str
    file_name: str
    status: IngestStatus
    chunk_count: Optional[int] = None
    progress: int = Field(default=0, ge=0, le=100, description="0-100 indexing progress")
    error: Optional[str] = None
    created_at: datetime
    completed_at: Optional[datetime] = None


# ---------------------------------------------------------------------------
# Health check
# ---------------------------------------------------------------------------

class HealthResponse(BaseModel):
    status: str = "ok"
    version: str = "1.0.0"
    environment: str
    vector_store: str
    llm_provider: str
    embedding_provider: str
